// Builds the Supabase (Postgres) setup SQL from schema.ts, so the tables always match the app.
// `npm run supabase:sql` writes it to supabase/schema.sql; a test checks that file is up to date.
// The SQL is safe to run again: it only adds what is missing (new tables, new columns).

import { BOOLEAN_COLUMNS, HEADERS, ID_COLUMN, NUMBER_COLUMNS, TABS, type TabKey } from "./schema";

/** Postgres table for a tab: the sheet tab name in lower case (e.g. Daily_Costs -> daily_costs). */
export function tableName(tab: TabKey): string {
  return TABS[tab].toLowerCase();
}

function columnType(col: string): string {
  if (BOOLEAN_COLUMNS.has(col)) return "boolean not null default false";
  if (NUMBER_COLUMNS.has(col)) return "numeric not null default 0";
  return "text not null default ''";
}

export function supabaseSchemaSql(): string {
  const tabs = Object.keys(TABS) as TabKey[];
  const out: string[] = [
    "-- MO Cafe & Villa – Supabase tables.",
    "-- Generated from src/lib/data/schema.ts by `npm run supabase:sql` – do not edit by hand.",
    "-- Run it in Supabase > SQL Editor. Safe to run again (only adds missing tables and columns).",
    "-- Only the app's server (secret key) can read or write: row level security is on with no policies.",
    "",
  ];
  for (const tab of tabs) {
    const t = `public.${tableName(tab)}`;
    const id = ID_COLUMN[tab];
    out.push(`-- ${TABS[tab]}`);
    out.push(`create table if not exists ${t} (`);
    out.push(`  seq bigint generated by default as identity, -- keeps rows in the order they were added`);
    out.push(`  "${id}" text not null primary key`);
    out.push(`);`);
    for (const col of HEADERS[tab]) {
      if (col === id) continue;
      out.push(`alter table ${t} add column if not exists "${col}" ${columnType(col)};`);
    }
    out.push(`create index if not exists ${tableName(tab)}_seq_idx on ${t} (seq);`);
    out.push(`alter table ${t} enable row level security;`);
    out.push(`revoke all on ${t} from anon, authenticated;`);
    out.push(`grant all on ${t} to service_role;`);
    out.push("");
  }
  const list = tabs.map((t) => `'${tableName(t)}'`).join(", ");
  out.push(
    "-- Replace all rows of one table in a single transaction (Settings / Targets / Users editing).",
    "create or replace function public.mo_replace_all(tbl text, rows jsonb)",
    "returns void language plpgsql security definer set search_path = public as $$",
    "declare cols text;",
    "begin",
    `  if tbl not in (${list}) then`,
    "    raise exception 'mo_replace_all: unknown table %', tbl;",
    "  end if;",
    "  select string_agg(quote_ident(column_name), ', ' order by ordinal_position) into cols",
    "    from information_schema.columns",
    "    where table_schema = 'public' and table_name = tbl and column_name <> 'seq';",
    "  execute format('delete from public.%I where true', tbl);",
    "  execute format('insert into public.%I (%s) select %s from jsonb_populate_recordset(null::public.%I, $1)', tbl, cols, cols, tbl)",
    "    using rows;",
    "end $$;",
    "revoke all on function public.mo_replace_all(text, jsonb) from public, anon, authenticated;",
    "grant execute on function public.mo_replace_all(text, jsonb) to service_role;",
    "",
    "notify pgrst, 'reload schema';",
    "",
  );
  return out.join("\n");
}
